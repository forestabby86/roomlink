'use strict';
const assert = require('node:assert/strict');
const {decodeRoom, formatTime, parseZoomLink} = require('./api/_shared');
const card = require('./api/card');
const room = require('./api/room');
const data = [1,'What’s the Point','Daily','09:00','America/Chicago','1234567890','DEMO','', 'https://us02web.zoom.us/j/1234567890?pwd=example'];
const code = Buffer.from(JSON.stringify(data)).toString('base64url');
assert.equal(decodeRoom(code).name,'What’s the Point');
assert.equal(formatTime('00:09'),'12:09 AM');
assert.equal(formatTime('17:30'),'5:30 PM');
assert.equal(decodeRoom('invalid'),null);
assert.equal(decodeRoom(Buffer.from(JSON.stringify([...data.slice(0,8),'https://zoom.us.evil.com/j/2'])).toString('base64url')),null);
assert.equal(parseZoomLink('https://us02web.zoom.us/j/1234567890').hostname,'us02web.zoom.us');
assert.equal(parseZoomLink('javascript:alert(1)'),null);
assert.equal(parseZoomLink('https://zoom.us.evil.com/j/42'),null);
assert.ok(card._svg(decodeRoom(code)).includes('What’s the Point'));
const mkRes = () => ({ statusCode:0, headers:{}, setHeader(k,v){this.headers[k]=v;},end(b){this.body=b;} });
(async()=>{
  const htmlRes=mkRes();
  await room({query:{code},headers:{host:'localhost:3000'}},htmlRes);
  assert.equal(htmlRes.statusCode,200);
  assert.ok(htmlRes.body.includes(`http://localhost:3000/og/${code}`));
  assert.ok(htmlRes.body.includes('Zoom meeting →'));
  const pngRes=mkRes();
  await card({query:{code},headers:{}},pngRes);
  assert.equal(pngRes.statusCode,200);
  assert.equal(pngRes.headers['Content-Type'],'image/png');
  assert.equal(pngRes.body.subarray(1,4).toString(),'PNG');
  assert.ok(pngRes.body.length<300*1024,`PNG should be compact: ${pngRes.body.length} bytes`);
  console.log(`All tests passed. Image size: ${(pngRes.body.length/1024).toFixed(1)} KiB.`);
})();
